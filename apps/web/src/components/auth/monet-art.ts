const LAST_MONET_KEY = 'prims:auth:last-painting';

interface MonetCycle {
  readonly order: readonly number[];
  readonly nextOrder: readonly number[];
  readonly cursor: number;
  readonly previous: number | null;
}

function swapArt(order: number[], firstIndex: number, secondIndex: number) {
  const first = order[firstIndex];
  const second = order[secondIndex];
  if (first === undefined || second === undefined) return;
  order[firstIndex] = second;
  order[secondIndex] = first;
}

function shuffleMonetArt(previous: number | null): number[] {
  const order = MONET_ART.map((_, index) => index);
  for (let index = order.length - 1; index > 0; index -= 1) {
    swapArt(order, index, Math.floor(Math.random() * (index + 1)));
  }
  if (order.length > 1 && order[0] === previous) {
    swapArt(order, 0, 1 + Math.floor(Math.random() * (order.length - 1)));
  }
  return order;
}

function lastMonetArtwork(): number | null {
  try {
    const saved = sessionStorage.getItem(LAST_MONET_KEY);
    if (saved === null) return null;
    const index = Number(saved);
    return Number.isInteger(index) && index >= 0 && index < MONET_ART.length ? index : null;
  } catch { return null; }
}

export function rememberMonetArtwork(index: number) {
  try { sessionStorage.setItem(LAST_MONET_KEY, String(index)); } catch { /* Optional session storage. */ }
}

export function createMonetCycle(): MonetCycle {
  const order = shuffleMonetArt(lastMonetArtwork());
  return { order, nextOrder: shuffleMonetArt(order[order.length - 1] ?? null), cursor: 0, previous: null };
}

export function currentMonetIndex(cycle: MonetCycle): number {
  return cycle.order[cycle.cursor] ?? 0;
}

export function nextMonetIndex(cycle: MonetCycle): number {
  return cycle.order[cycle.cursor + 1] ?? cycle.nextOrder[0] ?? 0;
}

export function advanceMonetCycle(cycle: MonetCycle): MonetCycle {
  const previous = currentMonetIndex(cycle);
  if (cycle.cursor + 1 < cycle.order.length) return { ...cycle, cursor: cycle.cursor + 1, previous };
  return {
    order: cycle.nextOrder,
    nextOrder: shuffleMonetArt(cycle.nextOrder[cycle.nextOrder.length - 1] ?? null),
    cursor: 0,
    previous,
  };
}
